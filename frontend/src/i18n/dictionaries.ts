/**
 * Translate a trimmed English phrase core to Thai.
 * Returns null when no exact phrase or pattern rule matches
 * (numbers, currency, tickers, user content, etc. stay untouched).
 */
export function translatePhraseToThai(core: string): string | null {
  if (!core) return null
  const exact = EXACT_PHRASE_MAP[core] ?? EXACT_PHRASE_MAP[core.toLowerCase()]
  if (exact) return exact
  for (const rule of PATTERN_RULES) {
    const match = core.match(rule.pattern)
    if (match) return rule.translate(match)
  }
  return null
}
